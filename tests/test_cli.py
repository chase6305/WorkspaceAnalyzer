def test_cli_uncompressed_cache_and_default_replay(tmp_path):
    from zipfile import ZIP_STORED, ZipFile

    args = [
        str(URDF),
        "--backend",
        "numpy",
        "--samples",
        "4",
        "--cache-dir",
        str(tmp_path),
    ]
    first = main([*args, "--cache-uncompressed"])
    with ZipFile(next(tmp_path.rglob("*.npz"))) as archive:
        assert all(info.compress_type == ZIP_STORED for info in archive.infolist())
    second = main(args)
    assert second.metadata["cache_hit"]
    np.testing.assert_array_equal(second.points, first.points)


