def test_console_entrypoint_exits_successfully_without_printing_result_object():
    # Match the sys.exit wrapper generated by the package installer.
    completed = subprocess.run(
        [
            sys.executable,
            "-c",
            "import sys; from workspace_analyzer.cli import entrypoint; "
            "sys.exit(entrypoint())",
            str(URDF),
            "--backend",
            "numpy",
            "--samples",
            "1",
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    assert completed.returncode == 0, completed.stderr
    assert completed.stderr == ""
    assert "1 samples | 2 DoF | numpy:cpu" in completed.stdout


