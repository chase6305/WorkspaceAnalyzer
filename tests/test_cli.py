@pytest.mark.parametrize("extension", ["npy", "npz", "csv"])
def test_target_cli_writes_quality_report_and_result(extension, tmp_path, capsys):
    targets = np.array([[0, 0, 0], [0.95, 0, 0], [2, 0, 0]])
    path = tmp_path / f"targets.{extension}"
    if extension == "npy":
        np.save(path, targets)
    elif extension == "npz":
        np.savez(path, targets=targets, weights=[1, 2, 4], base_from_targets=np.eye(4))
    else:
        np.savetxt(path, targets, delimiter=",")
    report_path, result_path = tmp_path / "report.json", tmp_path / "result.npz"
    result = main(
        [
            str(URDF.with_name("cartesian_stage.urdf")),
            "--backend",
            "numpy",
            "--mode",
            "targets",
            "--targets",
            str(path),
            "--batch-size",
            "2",
            "--ik-restarts",
            "1",
            "--ik-rescue-restarts",
            "0",
            "--min-joint-limit-margin",
            ".1",
            "--report",
            str(report_path),
            "--output",
            str(result_path),
        ]
    )
    report = json.loads(report_path.read_text())["assessment"]
    assert report["ik_success_count"] == 2
    assert report["quality_pass_count"] == 1
    assert report["weighted_quality_pass_rate"] == pytest.approx(
        1 / (7 if extension == "npz" else 3)
    )
    restored = AnalysisResult.load(result_path)
    np.testing.assert_array_equal(
        restored.metrics["quality_pass"], result.metrics["quality_pass"]
    )
    assert "quality accepted: 33.3%" in capsys.readouterr().out


